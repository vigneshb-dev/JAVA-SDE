package com.backendlearninglab;

import com.backendlearninglab.exception.InsufficientStockException;
import com.backendlearninglab.model.Inventory;
import com.backendlearninglab.model.Order;
import com.backendlearninglab.model.Product;
import com.backendlearninglab.model.User;
import com.backendlearninglab.model.UserRole;
import com.backendlearninglab.repository.JdbcOrderRepository;
import com.backendlearninglab.repository.JdbcProductRepository;
import com.backendlearninglab.repository.JdbcUserRepository;
import com.backendlearninglab.repository.OrderRepository;
import com.backendlearninglab.repository.ProductRepository;
import com.backendlearninglab.repository.UserRepository;
import com.backendlearninglab.service.OrderService;
import com.backendlearninglab.util.ConnectionManager;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import javax.sql.DataSource;
import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Integration Test validating ACID Transaction boundaries and Rollback mechanics in OrderFlow.
 */
class OrderServiceTransactionTest {

    private DataSource dataSource;
    private UserRepository userRepository;
    private ProductRepository productRepository;
    private OrderRepository orderRepository;
    private OrderService orderService;

    @BeforeEach
    void setUp() throws SQLException {
        dataSource = ConnectionManager.createH2FallbackDataSource();

        try (Connection conn = dataSource.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute("DROP ALL OBJECTS");
            stmt.execute("CREATE TABLE users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email VARCHAR(255) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL, full_name VARCHAR(150) NOT NULL, role VARCHAR(30) NOT NULL, status VARCHAR(20) NOT NULL, created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL)");
            stmt.execute("CREATE TABLE products (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sku VARCHAR(64) NOT NULL UNIQUE, name VARCHAR(255) NOT NULL, description TEXT, price NUMERIC(12, 2) NOT NULL, category VARCHAR(100) NOT NULL, is_active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL)");
            stmt.execute("CREATE TABLE inventory (product_id BIGINT PRIMARY KEY, available_stock INT NOT NULL DEFAULT 0, reserved_stock INT NOT NULL DEFAULT 0, warehouse_location VARCHAR(100), last_restocked_at TIMESTAMP)");
            stmt.execute("CREATE TABLE orders (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_number VARCHAR(64) NOT NULL UNIQUE, user_id BIGINT NOT NULL, status VARCHAR(30) NOT NULL, total_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.00, shipping_address TEXT NOT NULL, created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL)");
            stmt.execute("CREATE TABLE order_items (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL, product_id BIGINT NOT NULL, quantity INT NOT NULL, unit_price NUMERIC(12, 2) NOT NULL, subtotal NUMERIC(12, 2) NOT NULL)");
        }

        userRepository = new JdbcUserRepository(dataSource);
        productRepository = new JdbcProductRepository(dataSource);
        orderRepository = new JdbcOrderRepository(dataSource);
        orderService = new OrderService(dataSource, userRepository, productRepository, orderRepository);
    }

    @Test
    @DisplayName("Successfully place order: Inventory reserved and order items persisted")
    void testSuccessfulOrderPlacement() {
        User user = userRepository.save(new User("buyer@example.com", "hash", "Bob Buyer", UserRole.CUSTOMER));
        Product monitor = productRepository.save(new Product("MON-01", "Gaming Monitor", "144Hz", new BigDecimal("250.00"), "TECH"));
        productRepository.saveInventory(new Inventory(monitor.getId(), 5, 0, "WH-1", null));

        Order order = orderService.placeOrder(user.getId(), "100 Pine Street",
                List.of(new OrderService.OrderItemRequest(monitor.getId(), 2)));

        assertNotNull(order.getId());
        assertEquals(new BigDecimal("500.00"), order.getTotalAmount());
        assertEquals(1, order.getItems().size());

        Inventory updatedInv = productRepository.findInventoryByProductId(monitor.getId()).orElseThrow();
        assertEquals(3, updatedInv.getAvailableStock());
        assertEquals(2, updatedInv.getReservedStock());
    }

    @Test
    @DisplayName("Transaction Rollback: Order fails due to insufficient stock, no partial rows saved")
    void testTransactionRollbackOnInsufficientStock() {
        User user = userRepository.save(new User("buyer2@example.com", "hash", "Bob Buyer", UserRole.CUSTOMER));
        Product chair = productRepository.save(new Product("CHR-01", "Office Chair", "Mesh", new BigDecimal("150.00"), "FURNITURE"));
        productRepository.saveInventory(new Inventory(chair.getId(), 2, 0, "WH-1", null));

        assertThrows(InsufficientStockException.class, () -> {
            orderService.placeOrder(user.getId(), "100 Pine Street",
                    List.of(new OrderService.OrderItemRequest(chair.getId(), 5))); // Requested 5, only 2 available
        });

        // Verify stock was untouched
        Inventory untouchedInv = productRepository.findInventoryByProductId(chair.getId()).orElseThrow();
        assertEquals(2, untouchedInv.getAvailableStock());
        assertEquals(0, untouchedInv.getReservedStock());

        // Verify no order was left in the database
        List<Order> orders = orderRepository.findByUserId(user.getId());
        assertTrue(orders.isEmpty(), "No order should exist after rollback");
    }
}
