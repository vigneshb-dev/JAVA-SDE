package com.backendlearninglab.jdbc.demo;

import com.backendlearninglab.util.ConnectionManager;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import javax.sql.DataSource;
import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * EDUCATIONAL DEMO: ACID Transactions, Rollbacks, and Batch Processing in JDBC.
 * <p>
 * This class demonstrates:
 * 1. Default JDBC behavior: Auto-Commit mode (each statement is committed instantly).
 * 2. Manual Transaction Control: setAutoCommit(false), commit(), rollback().
 * 3. Batch Inserts: Grouping hundreds of SQL statements into a single network packet.
 * 4. Key Generation: Retrieving auto-increment Primary Keys generated by PostgreSQL/H2 sequences.
 */
public class JdbcTransactionAndBatchDemo {

    private static final Logger log = LoggerFactory.getLogger(JdbcTransactionAndBatchDemo.class);

    public static void main(String[] args) {
        System.out.println("=== JDBC TRANSACTIONS & BATCH PROCESSING ===");

        DataSource ds = ConnectionManager.createH2FallbackDataSource();
        setupSchema(ds);

        // 1. Transaction Rollback Demo: Simulating a mid-checkout crash
        demonstrateTransactionRollback(ds);

        // 2. Batch Execution Demo: Bulk inserting products efficiently
        demonstrateBatchInsertion(ds);
    }

    /**
     * ACID TRANSACTION ROLLBACK DEMO
     * <p>
     * Scenario: A customer places an order.
     * Step 1: Insert order record.
     * Step 2: Attempt to deduct inventory (Simulate an unexpected error / out-of-stock).
     * Result: Step 1 MUST NOT persist! The order record must be cleanly rolled back.
     */
    private static void demonstrateTransactionRollback(DataSource ds) {
        System.out.println("\n[1] Demonstrating Transaction Rollback on Failure:");

        String insertOrderSql = "INSERT INTO orders (order_number, total_amount) VALUES (?, ?)";

        try (Connection conn = ds.getConnection()) {
            // STEP 1: Disable Auto-Commit mode. From this moment, all SQL runs in a single transaction.
            conn.setAutoCommit(false);

            try (PreparedStatement pstmt = conn.prepareStatement(insertOrderSql, Statement.RETURN_GENERATED_KEYS)) {
                pstmt.setString(1, "ORD-TX-001");
                pstmt.setBigDecimal(2, new BigDecimal("199.99"));
                pstmt.executeUpdate();

                // Retrieve generated ID
                long generatedOrderId = -1;
                try (ResultSet keys = pstmt.getGeneratedKeys()) {
                    if (keys.next()) {
                        generatedOrderId = keys.getLong(1);
                        System.out.println("  Inserted order with generated ID: " + generatedOrderId);
                    }
                }

                // STEP 2: Simulate failure (e.g. inventory constraint violated or network crash)
                System.out.println("  Simulating business rule failure: Insufficient inventory!");
                boolean inventoryFailed = true;
                if (inventoryFailed) {
                    throw new RuntimeException("Warehouse system rejected item allocation!");
                }

                // STEP 3: If all steps succeed, commit changes permanently
                conn.commit();
                System.out.println("  Transaction committed successfully.");

            } catch (Exception e) {
                // STEP 4: Exception occurred -> ROLLBACK everything to maintain Consistency
                System.out.println("  Error occurred (" + e.getMessage() + ") -> Rolling back transaction!");
                conn.rollback();
            } finally {
                // Restore auto-commit before returning connection to the pool
                conn.setAutoCommit(true);
            }

            // Verify order was indeed NOT saved
            try (Statement checkStmt = conn.createStatement();
                 ResultSet rs = checkStmt.executeQuery("SELECT COUNT(*) AS total FROM orders WHERE order_number = 'ORD-TX-001'")) {
                if (rs.next()) {
                    System.out.println("  Verification check: Total orders in DB with this number = " + rs.getInt("total") + " (Expected: 0)");
                }
            }

        } catch (SQLException e) {
            log.error("Database connection failure", e);
        }
    }

    /**
     * BATCH PROCESSING DEMO
     * <p>
     * WHY USE BATCHING?
     * Executing 1,000 individual `pstmt.executeUpdate()` calls sends 1,000 separate TCP network
     * packets to the database server, incurring round-trip network latency on each.
     * `addBatch()` buffers commands in memory and sends them in a single network round-trip.
     */
    private static void demonstrateBatchInsertion(DataSource ds) {
        System.out.println("\n[2] Demonstrating Batch Insertion of 5 Products:");

        String sql = "INSERT INTO test_products (sku, name, price) VALUES (?, ?, ?)";

        try (Connection conn = ds.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {

            conn.setAutoCommit(false);

            for (int i = 1; i <= 5; i++) {
                pstmt.setString(1, "SKU-BATCH-" + i);
                pstmt.setString(2, "Batch Item #" + i);
                pstmt.setBigDecimal(3, new BigDecimal("19.99").multiply(BigDecimal.valueOf(i)));
                // Adds parameters to the internal driver batch buffer
                pstmt.addBatch();
            }

            // Send all 5 insert statements to database in a single round-trip
            int[] affectedRows = pstmt.executeBatch();
            conn.commit();

            System.out.println("  Successfully executed batch! Statement count: " + affectedRows.length);

        } catch (SQLException e) {
            log.error("Batch insert failed", e);
        }
    }

    private static void setupSchema(DataSource ds) {
        try (Connection conn = ds.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute("CREATE TABLE IF NOT EXISTS orders (" +
                    "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "order_number VARCHAR(64) NOT NULL, " +
                    "total_amount NUMERIC(12,2))");
            stmt.execute("CREATE TABLE IF NOT EXISTS test_products (" +
                    "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "sku VARCHAR(64) NOT NULL, " +
                    "name VARCHAR(150), " +
                    "price NUMERIC(12,2))");
        } catch (SQLException e) {
            log.error("Schema creation failed", e);
        }
    }
}
